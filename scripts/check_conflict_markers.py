#!/usr/bin/env python3
"""
Проверка: ни один отслеживаемый файл в РЕПОЗИТОРИИ (от корня, не от
текущего каталога — см. ниже) не содержит строку с маркером конфликта
слияния.

T-M1-51: 24.09.2026 при слиянии PR #149 файл docs/tasks.md попал в main
со служебными маркерами git внутри (исправлено в PR #151) — ни тесты,
ни CI на такие строки не смотрели, поэтому ни один автоматический
механизм этого не заметил.

Область действия — весь репозиторий, не текущий каталог (PR #155
review, замечание 1): `git grep` без pathspec ищет от текущего каталога
и НИЖЕ, а не от корня репозитория — запуск из подкаталога (например,
`backend/`) молча пропускал бы конфликт у корня. Пофиксили pathspec'ом
`-- :/` (git-магия «от корня работника дерева»), а не сменой `cwd`
процесса на `git rev-parse --show-toplevel`: одно добавление к уже
существующему вызову `git grep`, без второго вызова `git` только чтобы
узнать, куда переходить. Воспроизведено и проверено прогоном из
подкаталога: `tests/test_check_conflict_markers.py::
test_conflict_at_repo_root_is_found_when_run_from_a_subdirectory`.

Четыре формы маркера, не три:
  - `<{7,}` в начале строки — СЕМЬ ИЛИ БОЛЬШЕ символов `<`, далее пробельный
    символ (класс `[[:space:]]`, не литеральный пробел — см. про CRLF
    ниже) или конец строки (`<<<<<<< HEAD`, но и голый `<<<<<<<` тоже,
    и `<<<<<<<<<` при нестандартном `conflict-marker-size`);
  - то же для `>{7,}` (`>>>>>>> origin/main`);
  - то же для `|{7,}` — маркер общей основы в стиле diff3/zdiff3
    (`||||||| base`), не упомянут в тексте задачи: если у кого-то из
    разработчиков `merge.conflictStyle = diff3`, закоммиченный конфликт
    будет содержать и его, а проверка без него ловила бы только
    половину;
  - строка, РОВНО равная семи знакам `=` (плюс необязательный один
    пробельный символ на конце — см. про CRLF) и ничему больше — а НЕ
    `{7,}`. Асимметрия с тремя другими формами намеренная (PR #155
    review, замечание 3): `{7,}` здесь ловил бы Markdown-подчёркивания
    заголовка первого уровня длиннее семи знаков, которые текст задачи
    прямо исключает из маркеров, а конфликт ЛЮБОЙ длины маркера всё
    равно ловится по открывающей (`<`) и закрывающей (`>`) строкам —
    строка-разделитель нестандартной длины остаётся непойманной сама по
    себе, но не единственным сигналом о конфликте в файле. Подчёркивание
    заголовка Markdown знаками `=` ДРУГОЙ длины (не семь) под это не
    попадает — проверено прогоном по репозиторию перед включением
    проверки: строк, состоящих только из `=` (любой длины), на момент
    T-M1-51 было ноль (детали — тело коммита T-M1-51).

CRLF (PR #155 review, замечание 2): файл с `\\r\\n` оставляет `\\r` в
содержимом СТРОКИ, как её видит `git grep` (перевод строки не
нормализуется) — без учёта этого `^={7}$` не совпадает НИКОГДА на таком
файле (после семи `=` всегда есть `\\r` перед истинным концом строки), а
голые (без метки после) маркеры `<`/`>`/`|` пропускаются целиком (после
семи символов маркера сразу `\\r`, не пробел и не конец строки).
Исправлено допуском ОДНОГО необязательного пробельного символа перед
истинным концом — классом `[[:space:]]`, НЕ экранированием `\\r`: в
POSIX ERE, который использует `git grep -E`, `\\r` не является
управляющей последовательностью (проверено: `git grep -E 'x\\r$'` не
находит `x\\r`, `git grep -E 'x[[:space:]]$'` находит). Промаркированные
строки (`<<<<<<< HEAD`) под CRLF уже совпадали и раньше (пробел перед
меткой — обычный пробел, не `\\r`), пострадала именно строка-разделитель
`=======` и голые маркеры без метки.

Каждый шаблон использует квантификатор (`{7,}`/`{7}`), а не семь
символов литералом подряд — иначе этот же файл, став отслеживаемым,
ловил бы сам себя.

Собственный файл проверки из области действия НЕ исключён и исключаться
не должен: дыра в файле, отвечающем за то, чтобы конфликт не попал в
main, была бы дырой ровно там, где она всего опаснее.

`git grep -I` пропускает бинарные файлы — подтверждено прогоном, а не
только документацией `git grep` (PR #155 review, замечание 4): тот же
файл с байтом `\\x00` и текстом маркера внутри без `-I` даёт `Binary
file ... matches` (совпадение засчитывается), с `-I` — не находится
вовсе. Воспроизведено в
`tests/test_check_conflict_markers.py::test_binary_file_with_marker_bytes_is_ignored`.

Все шесть обязательных случаев (маркеры по умолчанию с метками, diff3
`|||||||`, нестандартная длина маркера через `conflict-marker-size`,
CRLF с метками, CRLF без меток, запуск из подкаталога) и отрицательная
сторона (чистое дерево, близкие промахи, бинарный файл) —
`tests/test_check_conflict_markers.py` в backend (единственный
доступный сегодня прогонщик; БД для этого теста не нужна).
"""

from __future__ import annotations

import subprocess
import sys

# `{7,}`/`{7}` — квантификаторы, а не семь символов литералом подряд:
# см. докстринг выше.
_MARKER_PATTERNS = (
    r"^<{7,}([[:space:]]|$)",
    r"^>{7,}([[:space:]]|$)",
    r"^\|{7,}([[:space:]]|$)",
    r"^={7}[[:space:]]?$",
)


def main() -> int:
    cmd = ["git", "grep", "--no-color", "-I", "-n", "--full-name", "-E"]
    for pattern in _MARKER_PATTERNS:
        cmd += ["-e", pattern]
    # `-- :/` — от корня рабочего дерева, а не от текущего каталога
    # (см. докстринг, замечание 1).
    cmd += ["--", ":/"]

    result = subprocess.run(cmd, capture_output=True, text=True, check=False)

    # `git grep`: 0 — есть совпадения, 1 — совпадений нет, >1 — ошибка
    # вызова (не тот каталог, `git` не найден и т.п.) — коды в обратном
    # для нас смысле, не перепутать с "0 — успех" по конвенции shell.
    if result.returncode == 0:
        print(
            "Маркер конфликта слияния найден — до пуша/мержа удалить вручную:",
            file=sys.stderr,
        )
        print(result.stdout, end="", file=sys.stderr)
        return 1

    if result.returncode == 1:
        print("Маркеров конфликта слияния не найдено.")
        return 0

    print(f"git grep завершился с ошибкой (код {result.returncode}): {result.stderr}", file=sys.stderr)
    return result.returncode


if __name__ == "__main__":
    sys.exit(main())
