import { useSession } from "./useSession";

const DAY_FORMAT = /^(\d{4})-(\d{2})-(\d{2})$/;

/** Настоящая календарная дата `YYYY-MM-DD`, а не только её форма: месяц 01-12, день не больше
 * числа дней месяца (високосный год по григорианскому правилу). Форма одна пропускала не-даты
 * (`2026-02-30` уходил в `POST /deactivate` как `2026-03-02`, `0000-00-00` давал перечень годов
 * `[0, 1]`); разбор без `Date`/`dayjs` - их мягкий разбор сам переносит `02-30` на март. */
export function isCalendarDay(value: string): boolean {
  const match = DAY_FORMAT.exec(value);
  if (match === null) {
    return false;
  }
  const [year, month, day] = [Number(match[1]), Number(match[2]), Number(match[3])];
  if (year < 1 || month < 1 || month > 12 || day < 1) {
    return false;
  }
  const leap = (year % 4 === 0 && year % 100 !== 0) || year % 400 === 0;
  const daysInMonth = [31, leap ? 29 : 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31][month - 1];
  return day <= daysInMonth;
}

/** Бизнес-день сервера из сессии (`GET /api/auth/me`, `NFR-LOC-002`, `T-M2-36`/`T-M2-38`) в виде
 * `YYYY-MM-DD` - ЕДИНСТВЕННЫЙ источник «сегодня» для значений по умолчанию (год производственного
 * календаря, дата увольнения). Часы браузера для этого не читаются нигде (сторож
 * `browserClockGuard.test.ts`).
 *
 * День ОБНОВЛЯЕТСЯ вместе с каждым ответом `me`, а не фиксируется на сессию: `QueryClient`
 * создан без опций (`providers.tsx`), `useMe` их не переопределяет, поэтому `me` перезапрашивается
 * при возврате на вкладку и после `invalidateQueries(["me"])` (смена пароля, настройки LDAP).
 * Устаревание ограничено моментом последнего ответа `me`; полночь по поясу организации лечится
 * при следующем возврате на вкладку (`requirements.md` раздел 13 п. 38, решение заказчика).
 * Потребители, которым день не должен меняться под рукой, берут СНИМОК (окно деактивации в
 * `EmployeeCardPage`); календарь, наоборот, следует за днём. Продление сессии (`T-M1-56`) не должно
 * отменить обновление `me`.
 *
 * `null` - день не пришёл или это не календарная дата: тип обещает поле, но тело ответа клиент во
 * время выполнения не проверяет (`T-M2-25`), а старый бэкенд или старый кэш его не пришлёт.
 * Вызывающий обязан показать «день неизвестен», а НЕ подставить часы браузера. */
export function useBusinessDay(): string | null {
  const { today } = useSession();
  return typeof today === "string" && isCalendarDay(today) ? today : null;
}
