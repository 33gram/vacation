import { useSession } from "./useSession";

const DAY_FORMAT = /^\d{4}-\d{2}-\d{2}$/;

/** Бизнес-день сервера из сессии (`GET /api/auth/me`, `NFR-LOC-002`, `T-M2-36`/`T-M2-38`) в виде
 * `YYYY-MM-DD` - ЕДИНСТВЕННЫЙ источник «сегодня» для значений по умолчанию (год производственного
 * календаря, дата увольнения). Часы браузера для этого не читаются нигде (сторож
 * `browserClockGuard.test.ts`).
 *
 * День фиксируется на сессию: `me` запрашивается один раз (`SessionGate`), и вкладка, пережившая
 * полночь по поясу организации, держит вчерашний день до следующего входа (решение заказчика,
 * `requirements.md` раздел 13 п. 38; срок токена 60 минут от входа ограничивает устаревание).
 * Продление сессии (`T-M1-56`) обязано обновлять и `today`.
 *
 * `null` - день не пришёл или не похож на дату: тип обещает поле, но тело ответа клиент во время
 * выполнения не проверяет (`T-M2-25`), а старый бэкенд или старый кэш его не пришлёт. Вызывающий
 * обязан показать «день неизвестен», а НЕ подставить часы браузера. */
export function useBusinessDay(): string | null {
  const { today } = useSession();
  return typeof today === "string" && DAY_FORMAT.test(today) ? today : null;
}
